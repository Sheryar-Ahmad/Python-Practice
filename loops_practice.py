# for each loop
fruits = ["apple", "banana", "cherry"]
for fruit in fruits:
    print(fruit)

# for in loop
for i in range(5):
    print(i)

# for loop with index
for index, fruit in enumerate(fruits):
    print(index, fruit)
    
# for loop with dictionary
scores = {"Alice": 88, "Bob": 92}
for name, score in scores.items():
    print(name, score)
    
